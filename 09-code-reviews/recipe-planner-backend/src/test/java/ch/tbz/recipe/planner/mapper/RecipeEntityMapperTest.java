package ch.tbz.recipe.planner.mapper;

import ch.tbz.recipe.planner.domain.Ingredient;
import ch.tbz.recipe.planner.domain.Recipe;
import ch.tbz.recipe.planner.domain.Unit;
import ch.tbz.recipe.planner.entities.IngredientEntity;
import ch.tbz.recipe.planner.entities.RecipeEntity;
import org.assertj.core.api.SoftAssertions;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import static org.assertj.core.api.SoftAssertions.assertSoftly;

/**
 * Task 1: tests for the MapStruct mapper {@link RecipeEntityMapper} with AssertJ SoftAssertions,
 * including the nested list of ingredients.
 * <p>
 * Two styles are shown: {@code assertSoftly(softly -> ...)} and an explicit {@code SoftAssertions} object
 * with a final {@code assertAll()}.
 * </p>
 */
class RecipeEntityMapperTest {

    private RecipeEntityMapper mapper;
    private UUID recipeId;
    private UUID tomatoId;
    private UUID basilId;

    @BeforeEach
    void setUp() {
        // Implementation generated by MapStruct at compile time
        mapper = new RecipeEntityMapperImpl();
        recipeId = UUID.randomUUID();
        tomatoId = UUID.randomUUID();
        basilId = UUID.randomUUID();
    }

    private RecipeEntity pizzaEntity() {
        List<IngredientEntity> ingredients = new ArrayList<>(List.of(
                new IngredientEntity(tomatoId, "Tomato", "ripe", Unit.PIECE, 4),
                new IngredientEntity(basilId, "Basil", null, Unit.GRAMM, 10)));
        return new RecipeEntity(recipeId, "Pizza Margherita", "Classic pizza", "https://example.com/pizza.jpg", ingredients);
    }

    @Test
    @DisplayName("entityToDomain maps all recipe fields and the nested ingredients")
    void entityToDomain() {
        Recipe recipe = mapper.entityToDomain(pizzaEntity());

        assertSoftly(softly -> {
            softly.assertThat(recipe.getId()).isEqualTo(recipeId);
            softly.assertThat(recipe.getName()).isEqualTo("Pizza Margherita");
            softly.assertThat(recipe.getDescription()).isEqualTo("Classic pizza");
            softly.assertThat(recipe.getImageUrl()).isEqualTo("https://example.com/pizza.jpg");
            softly.assertThat(recipe.getIngredients()).hasSize(2);

            Ingredient tomato = recipe.getIngredients().get(0);
            softly.assertThat(tomato.getId()).isEqualTo(tomatoId);
            softly.assertThat(tomato.getName()).isEqualTo("Tomato");
            softly.assertThat(tomato.getComment()).isEqualTo("ripe");
            softly.assertThat(tomato.getUnit()).isEqualTo(Unit.PIECE);
            softly.assertThat(tomato.getAmount()).isEqualTo(4);

            Ingredient basil = recipe.getIngredients().get(1);
            softly.assertThat(basil.getName()).isEqualTo("Basil");
            softly.assertThat(basil.getComment()).isNull();
            softly.assertThat(basil.getUnit()).isEqualTo(Unit.GRAMM);
        });
    }

    @Test
    @DisplayName("domainToEntity maps all recipe fields and the nested ingredients")
    void domainToEntity() {
        Recipe recipe = new Recipe(recipeId, "Pancakes", "Sweet breakfast", "img.png",
                List.of(new Ingredient(tomatoId, "Milk", null, Unit.DECILITRE, 3)));

        RecipeEntity entity = mapper.domainToEntity(recipe);

        SoftAssertions softly = new SoftAssertions();
        softly.assertThat(entity.getId()).isEqualTo(recipeId);
        softly.assertThat(entity.getName()).isEqualTo("Pancakes");
        softly.assertThat(entity.getDescription()).isEqualTo("Sweet breakfast");
        softly.assertThat(entity.getImageUrl()).isEqualTo("img.png");
        softly.assertThat(entity.getIngredients()).singleElement()
                .satisfies(ingredient -> {
                    softly.assertThat(ingredient.getId()).isEqualTo(tomatoId);
                    softly.assertThat(ingredient.getName()).isEqualTo("Milk");
                    softly.assertThat(ingredient.getUnit()).isEqualTo(Unit.DECILITRE);
                    softly.assertThat(ingredient.getAmount()).isEqualTo(3);
                });
        // Reports all failed assertions at once
        softly.assertAll();
    }

    @Test
    @DisplayName("a new recipe without ids keeps the ids null (generated later by the database)")
    void newRecipeWithoutIds() {
        Recipe recipe = new Recipe(null, "Soup", "Hot", null, List.of(new Ingredient(null, "Water", null, Unit.LITRE, 1)));

        RecipeEntity entity = mapper.domainToEntity(recipe);

        assertSoftly(softly -> {
            softly.assertThat(entity.getId()).isNull();
            softly.assertThat(entity.getImageUrl()).isNull();
            softly.assertThat(entity.getIngredients()).extracting(IngredientEntity::getId).containsOnlyNulls();
        });
    }

    @Test
    @DisplayName("recipe without ingredients: null stays null, empty list stays empty")
    void ingredientsNullOrEmpty() {
        assertSoftly(softly -> {
            softly.assertThat(mapper.entityToDomain(new RecipeEntity(recipeId, "A", "B", "C", null)).getIngredients()).isNull();
            softly.assertThat(mapper.entityToDomain(new RecipeEntity(recipeId, "A", "B", "C", List.of())).getIngredients()).isEmpty();
            softly.assertThat(mapper.domainToEntity(new Recipe(recipeId, "A", "B", "C", null)).getIngredients()).isNull();
        });
    }

    @Test
    @DisplayName("null input returns null; null ingredients inside the list stay null")
    void nullInput() {
        List<IngredientEntity> withNull = new ArrayList<>();
        withNull.add(null);
        List<Ingredient> domainWithNull = new ArrayList<>();
        domainWithNull.add(null);

        assertSoftly(softly -> {
            softly.assertThat(mapper.entityToDomain(null)).isNull();
            softly.assertThat(mapper.domainToEntity(null)).isNull();
            softly.assertThat(mapper.entityToDomain(new RecipeEntity(recipeId, "A", null, null, withNull)).getIngredients())
                    .containsExactly((Ingredient) null);
            softly.assertThat(mapper.domainToEntity(new Recipe(recipeId, "A", null, null, domainWithNull)).getIngredients())
                    .containsExactly((IngredientEntity) null);
        });
    }

    @Test
    @DisplayName("round trip entity -> domain -> entity keeps all values (deep copy)")
    void roundTrip() {
        RecipeEntity original = pizzaEntity();

        RecipeEntity result = mapper.domainToEntity(mapper.entityToDomain(original));

        assertSoftly(softly -> {
            softly.assertThat(result).usingRecursiveComparison().isEqualTo(original);
            softly.assertThat(result).isNotSameAs(original);
            softly.assertThat(result.getIngredients()).isNotSameAs(original.getIngredients());
        });
    }
}

