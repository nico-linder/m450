import axios from "axios";

/** Base URL of the recipe planner backend. */
export const API_BASE_URL = "http://localhost:8080/api/recipes";

/**
 * Loads all recipes.
 * @returns {Promise<Array>} list of recipes
 */
export const getRecipes = async () => {
    const response = await axios.get(API_BASE_URL);
    return response.data;
};

/**
 * Loads a single recipe.
 * The backend answers an unknown id with 200 and an empty body, therefore null is returned in this case.
 *
 * @param {string} id recipe id (UUID)
 * @returns {Promise<object|null>} the recipe, or null if it does not exist
 */
export const getRecipe = async (id) => {
    const response = await axios.get(`${API_BASE_URL}/recipe/${id}`);
    return response.data || null;
};

/**
 * Creates a new recipe. Ids are generated by the backend.
 * @param {object} recipe recipe with name, description, imageUrl and ingredients
 * @returns {Promise<object>} the created recipe including the generated ids
 */
export const createRecipe = async (recipe) => {
    const response = await axios.post(API_BASE_URL, recipe);
    return response.data;
};

/**
 * Updates an existing recipe (the backend answers 404 if it does not exist).
 * @param {string} id recipe id (UUID)
 * @param {object} recipe new values of the recipe
 * @returns {Promise<object>} the updated recipe
 */
export const updateRecipe = async (id, recipe) => {
    const response = await axios.put(`${API_BASE_URL}/${id}`, recipe);
    return response.data;
};
