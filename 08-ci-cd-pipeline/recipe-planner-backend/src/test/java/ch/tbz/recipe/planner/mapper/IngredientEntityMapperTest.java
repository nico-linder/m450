package ch.tbz.recipe.planner.mapper;

import ch.tbz.recipe.planner.domain.Ingredient;
import ch.tbz.recipe.planner.domain.Unit;
import ch.tbz.recipe.planner.entities.IngredientEntity;
import org.assertj.core.api.SoftAssertions;
import org.assertj.core.api.junit.jupiter.InjectSoftAssertions;
import org.assertj.core.api.junit.jupiter.SoftAssertionsExtension;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.EnumSource;

import java.util.List;
import java.util.UUID;

/**
 * Task 1: tests for the MapStruct mapper {@link IngredientEntityMapper} with AssertJ SoftAssertions.
 * <p>
 * With SoftAssertions all assertions of a test are executed, even if one fails. At the end, all failures are
 * reported together – for a mapper this shows at once which fields are mapped wrongly instead of only the first one.
 * </p>
 */
@ExtendWith(SoftAssertionsExtension.class)
class IngredientEntityMapperTest {

    /** Injected by the SoftAssertionsExtension; assertAll() is called automatically after each test. */
    @InjectSoftAssertions
    private SoftAssertions softly;

    private IngredientEntityMapper mapper;
    private UUID id;

    @BeforeEach
    void setUp() {
        // Implementation generated by MapStruct at compile time
        mapper = new IngredientEntityMapperImpl();
        id = UUID.randomUUID();
    }

    @Test
    @DisplayName("entityToDomain maps all fields")
    void entityToDomain() {
        IngredientEntity entity = new IngredientEntity(id, "Tomato", "The big ones", Unit.PIECE, 5);

        Ingredient domain = mapper.entityToDomain(entity);

        softly.assertThat(domain).isNotNull();
        softly.assertThat(domain.getId()).isEqualTo(id);
        softly.assertThat(domain.getName()).isEqualTo("Tomato");
        softly.assertThat(domain.getComment()).isEqualTo("The big ones");
        softly.assertThat(domain.getUnit()).isEqualTo(Unit.PIECE);
        softly.assertThat(domain.getAmount()).isEqualTo(5);
    }

    @Test
    @DisplayName("domainToEntity maps all fields")
    void domainToEntity() {
        Ingredient domain = new Ingredient(id, "Flour", "Type 405", Unit.GRAMM, 500);

        IngredientEntity entity = mapper.domainToEntity(domain);

        softly.assertThat(entity).isNotNull();
        softly.assertThat(entity.getId()).isEqualTo(id);
        softly.assertThat(entity.getName()).isEqualTo("Flour");
        softly.assertThat(entity.getComment()).isEqualTo("Type 405");
        softly.assertThat(entity.getUnit()).isEqualTo(Unit.GRAMM);
        softly.assertThat(entity.getAmount()).isEqualTo(500);
    }

    @ParameterizedTest(name = "unit {0}")
    @EnumSource(Unit.class)
    @DisplayName("every unit is mapped in both directions")
    void allUnits(Unit unit) {
        Ingredient domain = new Ingredient(id, "Milk", null, unit, 1);

        softly.assertThat(mapper.domainToEntity(domain).getUnit()).isEqualTo(unit);
        softly.assertThat(mapper.entityToDomain(new IngredientEntity(id, "Milk", null, unit, 1)).getUnit()).isEqualTo(unit);
    }

    @Test
    @DisplayName("null values inside the object are kept as null")
    void nullFields() {
        Ingredient domain = mapper.entityToDomain(new IngredientEntity());

        softly.assertThat(domain.getId()).isNull();
        softly.assertThat(domain.getName()).isNull();
        softly.assertThat(domain.getComment()).isNull();
        softly.assertThat(domain.getUnit()).isNull();
        softly.assertThat(domain.getAmount()).isZero();
    }

    @Test
    @DisplayName("null input returns null instead of throwing an exception")
    void nullInput() {
        softly.assertThat(mapper.entityToDomain(null)).isNull();
        softly.assertThat(mapper.domainToEntity(null)).isNull();
        softly.assertThat(mapper.entitiesToDomains(null)).isNull();
        softly.assertThat(mapper.domainsToEntities(null)).isNull();
    }

    @Test
    @DisplayName("lists are mapped element by element and keep their order")
    void lists() {
        List<IngredientEntity> entities = List.of(
                new IngredientEntity(UUID.randomUUID(), "Tomato", null, Unit.PIECE, 3),
                new IngredientEntity(UUID.randomUUID(), "Water", null, Unit.LITRE, 1));

        List<Ingredient> domains = mapper.entitiesToDomains(entities);

        softly.assertThat(domains).hasSize(2);
        softly.assertThat(domains).extracting(Ingredient::getName).containsExactly("Tomato", "Water");
        softly.assertThat(domains).extracting(Ingredient::getUnit).containsExactly(Unit.PIECE, Unit.LITRE);

        List<IngredientEntity> back = mapper.domainsToEntities(domains);
        softly.assertThat(back).usingRecursiveFieldByFieldElementComparator().isEqualTo(entities);
        softly.assertThat(mapper.entitiesToDomains(List.of())).isEmpty();
    }

    @Test
    @DisplayName("round trip domain -> entity -> domain returns an equal object")
    void roundTrip() {
        Ingredient original = new Ingredient(id, "Butter", "unsalted", Unit.GRAMM, 250);

        Ingredient result = mapper.entityToDomain(mapper.domainToEntity(original));

        softly.assertThat(result).isEqualTo(original).isNotSameAs(original);
    }
}

